// Shared lesson model used by the Worker (validation) and the browser (playback).
//
// A lesson is a list of steps (chapters). Each step is a list of beats. A beat
// is one short spoken phrase plus the whiteboard actions that happen while it
// is spoken. Narration audio is generated per beat, so the measured length of
// each clip decides exactly when its drawings appear.

/** The whiteboard uses a fixed logical canvas: x 0..100 (left→right), y 0..62 (top→bottom). */
export const BOARD_W = 100;
export const BOARD_H = 62;

export const COLORS = ['ink', 'blue', 'red', 'green', 'orange', 'purple'] as const;
export type Color = (typeof COLORS)[number];

export const SIZES = ['sm', 'md', 'lg'] as const;
export type Size = (typeof SIZES)[number];

export const OPS = ['text', 'box', 'circle', 'graph', 'arrow', 'line', 'underline', 'highlight', 'cross', 'move', 'erase', 'clear'] as const;
export type Op = (typeof OPS)[number];

/**
 * One whiteboard instruction.
 * - text / box / circle create a named item centred on (x, y).
 * - arrow / line connect two items (from/to ids) or two points (x,y → x2,y2).
 * - graph draws axes with plotted points (a line chart) centred on (x, y), size w × h.
 * - underline draws a stroke under an existing item (target).
 * - cross strikes out an existing item (eliminated, wrong, cancelled); it stays visible, dimmed.
 * - move slides an existing item (target) so its centre ends at (x, y).
 * - highlight emphasises an existing item while its beat is spoken (target).
 * - erase removes one item (target); clear wipes the board.
 */
export interface Action {
  op: Op;
  id?: string;
  text?: string;
  x?: number;
  y?: number;
  x2?: number;
  y2?: number;
  w?: number;
  h?: number;
  r?: number;
  from?: string;
  to?: string;
  target?: string;
  color?: Color;
  size?: Size;
  /** graph only: data points as [x, y] pairs, in data units. */
  points?: [number, number][];
}

export interface Beat {
  id: string;
  say: string;
  actions: Action[];
}

export interface Step {
  id: string;
  title: string;
  beats: Beat[];
}

export interface QuizQuestion {
  q: string;
  options: string[];
  answer: number;
  why: string;
}

export type Level = 'beginner' | 'intermediate' | 'advanced';

export interface Lesson {
  id: string;
  topic: string;
  title: string;
  level: Level;
  summary: string;
  steps: Step[];
  quiz: QuizQuestion[];
  /** 'live' = generated by Workers AI for this request; 'sample' = pre-generated and shipped with the app. */
  source: 'live' | 'sample';
  model?: string;
  /** Sample lessons only: file extension of the stored narration clips. */
  audio?: 'wav' | 'mp3';
  /** Narration voice: 'premium' (Aura-2) or 'economy' (MeloTTS: the default, and the fallback once an Aura-2 budget is spent). */
  voiceTier?: VoiceTier;
  /** True when served from the topic cache (generated earlier for someone else). */
  cached?: boolean;
  /** Where the lesson text was written: Cloudflare Workers AI, or an open model in the learner's browser. */
  generatedOn?: 'cloud' | 'device';
}

export type VoiceTier = 'premium' | 'economy';

export interface AskRequest {
  topic: string;
  lessonTitle: string;
  stepTitle: string;
  /** Narration the learner has heard so far in the current step. */
  context: string;
  /** Items currently on the board, so the tutor can point at them. */
  board: { id: string; label: string }[];
  selectedId?: string;
  /** Items the learner circled or marked with the pen before asking. */
  circled?: string[];
  question: string;
  history: { role: 'user' | 'tutor'; text: string }[];
}

export interface AskResponse {
  answer: string;
  highlight: string[];
  voiceTier?: VoiceTier;
}

export interface ApiError {
  error: string;
  code: 'bad_request' | 'quota' | 'limit' | 'ai_failed' | 'invalid_output' | 'not_found' | 'server';
}
